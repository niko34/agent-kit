#!/usr/bin/env python3
"""Synchronise les profils Claude Code vers GitHub Copilot.

Les fichiers ``.claude/agents/*.md`` restent la source de vérité. Le script
génère leurs équivalents ``.github/agents/*.agent.md`` sans dépendance Python
externe.

Usage :
    python3 tools/sync_copilot_agents.py --write
    python3 tools/sync_copilot_agents.py --check
"""

from __future__ import annotations

import argparse
import ast
import json
import os
import re
import sys
import tempfile
from dataclasses import dataclass
from pathlib import Path
from typing import Sequence


SOURCE_DIRECTORY = Path(".claude/agents")
TARGET_DIRECTORY = Path(".github/agents")
GENERATOR_SIGNATURE = "Generated by tools/sync_copilot_agents.py"
COPILOT_PROMPT_LIMIT = 30_000
SUPPORTED_KEYS = {"name", "description", "tools"}

# Clés Claude délibérément NON transférées. Elles sont listées ici, et non
# ajoutées à SUPPORTED_KEYS, pour que le refus en bloc continue de protéger
# contre une clé réellement inconnue : « non convertie » doit rester une erreur,
# « non transférable » est une décision.
#
#   model — le choix du modèle est propre au runtime. Copilot choisit le sien ;
#           recopier « opus » ou « fable » dans un profil Copilot produirait une
#           valeur que rien ne lit, et qui mentirait au lecteur.
IGNORED_KEYS = {"model"}
AGENT_NAME_PATTERN = re.compile(r"^[A-Za-z0-9._-]+$")

# Les alias Claude sont officiellement compris par Copilot. Les normaliser vers
# les noms génériques garde néanmoins les profils générés lisibles et portables.
TOOL_ALIASES = {
    "read": "read",
    "notebookread": "read",
    "write": "edit",
    "edit": "edit",
    "multiedit": "edit",
    "notebookedit": "edit",
    "bash": "execute",
    "shell": "execute",
    "powershell": "execute",
    "execute": "execute",
    "grep": "search",
    "glob": "search",
    "search": "search",
    "task": "agent",
    "custom-agent": "agent",
    "agent": "agent",
    "websearch": "web",
    "webfetch": "web",
    "web": "web",
    "todowrite": "todo",
    "todo": "todo",
}


class ConversionError(Exception):
    """Erreur de définition empêchant une conversion sûre."""


@dataclass(frozen=True)
class AgentProfile:
    name: str
    description: str
    tools: tuple[str, ...]
    body: str
    source: Path


@dataclass(frozen=True)
class SyncResult:
    changed: tuple[str, ...] = ()
    issues: tuple[str, ...] = ()


def _parse_scalar(value: str, source: Path, line_number: int) -> str:
    value = value.strip()
    if not value:
        return ""
    if value[0] in {"'", '"'}:
        try:
            parsed = ast.literal_eval(value)
        except (SyntaxError, ValueError) as exc:
            raise ConversionError(
                f"{source}:{line_number}: chaîne YAML invalide: {value}"
            ) from exc
        if not isinstance(parsed, str):
            raise ConversionError(
                f"{source}:{line_number}: une chaîne était attendue"
            )
        return parsed
    return value


def _parse_frontmatter(header: str, source: Path) -> dict[str, object]:
    """Parse le sous-ensemble YAML volontairement limité utilisé par le kit."""
    metadata: dict[str, object] = {}
    current_list: str | None = None

    for line_number, line in enumerate(header.splitlines(), start=2):
        stripped = line.strip()
        if not stripped or stripped.startswith("#"):
            continue

        if line[0].isspace():
            if current_list is None or not stripped.startswith("- "):
                raise ConversionError(
                    f"{source}:{line_number}: YAML imbriqué non pris en charge"
                )
            item = _parse_scalar(stripped[2:], source, line_number)
            assert isinstance(metadata[current_list], list)
            metadata[current_list].append(item)
            continue

        key, separator, raw_value = line.partition(":")
        if not separator or not re.fullmatch(r"[A-Za-z][A-Za-z0-9_-]*", key):
            raise ConversionError(
                f"{source}:{line_number}: entrée de frontmatter invalide"
            )
        if key in metadata:
            raise ConversionError(f"{source}:{line_number}: clé dupliquée: {key}")
        if key in IGNORED_KEYS:
            current_list = None
            continue
        if key not in SUPPORTED_KEYS:
            raise ConversionError(
                f"{source}:{line_number}: clé Claude non convertie: {key}"
            )

        raw_value = raw_value.strip()
        if not raw_value:
            metadata[key] = []
            current_list = key
        else:
            metadata[key] = _parse_scalar(raw_value, source, line_number)
            current_list = None

    return metadata


def _parse_tools(value: object, source: Path) -> tuple[str, ...]:
    if isinstance(value, list):
        raw_tools = value
    elif isinstance(value, str):
        stripped = value.strip()
        if stripped.startswith("["):
            try:
                parsed = ast.literal_eval(stripped)
            except (SyntaxError, ValueError) as exc:
                raise ConversionError(
                    f"{source}: liste d'outils invalide: {value}"
                ) from exc
            if not isinstance(parsed, (list, tuple)):
                raise ConversionError(f"{source}: tools doit être une liste")
            raw_tools = list(parsed)
        else:
            raw_tools = [part.strip() for part in stripped.split(",")]
    else:
        raise ConversionError(f"{source}: tools doit être une chaîne ou une liste")

    converted: list[str] = []
    unknown: list[str] = []
    for raw_tool in raw_tools:
        if not isinstance(raw_tool, str) or not raw_tool.strip():
            raise ConversionError(f"{source}: nom d'outil vide ou invalide")
        tool = raw_tool.strip()
        mapped = TOOL_ALIASES.get(tool.casefold())
        if mapped is None:
            unknown.append(tool)
        elif mapped not in converted:
            converted.append(mapped)

    if unknown:
        raise ConversionError(
            f"{source}: outils sans équivalent Copilot: {', '.join(unknown)}"
        )
    return tuple(converted)


def parse_agent(source: Path) -> AgentProfile:
    text = source.read_text(encoding="utf-8")
    if not text.startswith("---\n"):
        raise ConversionError(f"{source}: frontmatter YAML ouvrant manquant")
    closing = text.find("\n---\n", 4)
    if closing == -1:
        raise ConversionError(f"{source}: frontmatter YAML fermant manquant")

    metadata = _parse_frontmatter(text[4:closing], source)
    missing = [key for key in ("name", "description", "tools") if key not in metadata]
    if missing:
        raise ConversionError(f"{source}: clés obligatoires absentes: {', '.join(missing)}")

    name = metadata["name"]
    description = metadata["description"]
    if not isinstance(name, str) or not AGENT_NAME_PATTERN.fullmatch(name):
        raise ConversionError(f"{source}: nom d'agent invalide: {name!r}")
    if source.stem != name:
        raise ConversionError(
            f"{source}: le nom '{name}' doit correspondre au nom du fichier"
        )
    if not isinstance(description, str) or not description.strip():
        raise ConversionError(f"{source}: description obligatoire")

    body = text[closing + len("\n---\n") :].strip()
    if not body:
        raise ConversionError(f"{source}: instructions de l'agent absentes")

    return AgentProfile(
        name=name,
        description=description.strip(),
        tools=_parse_tools(metadata["tools"], source),
        body=body,
        source=source,
    )


def _yaml_string(value: str) -> str:
    # Une chaîne JSON est aussi un scalaire YAML valide.
    return json.dumps(value, ensure_ascii=False)


def render_copilot_profile(profile: AgentProfile, root: Path) -> str:
    source_path = profile.source.relative_to(root).as_posix()
    description = profile.description.replace("Claude Code", "GitHub Copilot")
    lines = [
        "---",
        f"name: {_yaml_string(profile.name)}",
        f"description: {_yaml_string(description)}",
        "tools:",
    ]
    lines.extend(f"  - {tool}" for tool in profile.tools)
    lines.extend(
        [
            "---",
            f"<!-- {GENERATOR_SIGNATURE} from {source_path}; do not edit. -->",
            "",
            "## Adaptation GitHub Copilot",
            "",
            "Les mentions de Claude ou Claude Code dans les",
            "instructions partagées désignent l'agent de développement actif. Une",
            "notation Task(subagent_type=...) désigne l'invocation du profil Copilot",
            "correspondant. Les skills restent chargées depuis .claude/skills/.",
            "",
            profile.body,
            "",
        ]
    )
    rendered = "\n".join(lines)
    prompt = rendered.split("\n---\n", maxsplit=1)[1]
    if len(prompt) > COPILOT_PROMPT_LIMIT:
        raise ConversionError(
            f"{profile.source}: instructions Copilot trop longues "
            f"({len(prompt)} caractères, maximum {COPILOT_PROMPT_LIMIT})"
        )
    return rendered


def build_expected(root: Path) -> dict[Path, str]:
    source_dir = root / SOURCE_DIRECTORY
    if not source_dir.is_dir():
        raise ConversionError(f"dossier source absent: {source_dir}")

    sources = sorted(source_dir.glob("*.md"))
    if not sources:
        raise ConversionError(f"aucun agent Claude trouvé dans {source_dir}")

    expected: dict[Path, str] = {}
    for source in sources:
        profile = parse_agent(source)
        target = root / TARGET_DIRECTORY / f"{profile.name}.agent.md"
        if target in expected:
            raise ConversionError(f"cible Copilot dupliquée: {target}")
        expected[target] = render_copilot_profile(profile, root)
    return expected


def _is_generated(path: Path) -> bool:
    try:
        beginning = path.read_text(encoding="utf-8")[:2048]
    except (OSError, UnicodeError):
        return False
    return GENERATOR_SIGNATURE in beginning


def check_sync(root: Path) -> SyncResult:
    expected = build_expected(root)
    issues: list[str] = []

    for target, content in expected.items():
        relative = target.relative_to(root).as_posix()
        if not target.exists():
            issues.append(f"profil manquant: {relative}")
        elif target.read_text(encoding="utf-8") != content:
            issues.append(f"profil périmé: {relative}")

    target_dir = root / TARGET_DIRECTORY
    if target_dir.is_dir():
        for target in sorted(target_dir.glob("*.agent.md")):
            if target not in expected and _is_generated(target):
                issues.append(
                    f"profil généré orphelin: {target.relative_to(root).as_posix()}"
                )

    return SyncResult(issues=tuple(issues))


def _atomic_write(path: Path, content: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    descriptor, temporary_name = tempfile.mkstemp(
        prefix=f".{path.name}.", suffix=".tmp", dir=path.parent
    )
    temporary = Path(temporary_name)
    try:
        with os.fdopen(descriptor, "w", encoding="utf-8", newline="\n") as handle:
            handle.write(content)
        os.replace(temporary, path)
    finally:
        if temporary.exists():
            temporary.unlink()


def write_sync(root: Path) -> SyncResult:
    expected = build_expected(root)

    collisions = [
        target.relative_to(root).as_posix()
        for target in expected
        if target.exists() and not _is_generated(target)
    ]
    if collisions:
        raise ConversionError(
            "refus d'écraser des profils Copilot non générés: " + ", ".join(collisions)
        )

    changed: list[str] = []
    for target, content in expected.items():
        if not target.exists() or target.read_text(encoding="utf-8") != content:
            _atomic_write(target, content)
            changed.append(f"écrit: {target.relative_to(root).as_posix()}")

    target_dir = root / TARGET_DIRECTORY
    if target_dir.is_dir():
        for target in sorted(target_dir.glob("*.agent.md")):
            if target not in expected and _is_generated(target):
                target.unlink()
                changed.append(f"supprimé: {target.relative_to(root).as_posix()}")

    return SyncResult(changed=tuple(changed))


def _build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        description="Synchronise .claude/agents vers .github/agents pour Copilot."
    )
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--write", action="store_true", help="génère les profils Copilot")
    mode.add_argument(
        "--check",
        action="store_true",
        help="vérifie la synchronisation sans modifier de fichier",
    )
    parser.add_argument(
        "--root",
        type=Path,
        default=Path(__file__).resolve().parents[1],
        help="racine du dépôt (défaut: parent de tools/)",
    )
    return parser


def main(argv: Sequence[str] | None = None) -> int:
    args = _build_parser().parse_args(argv)
    root = args.root.resolve()
    try:
        if args.check:
            result = check_sync(root)
            if result.issues:
                print("❌ Profils GitHub Copilot non synchronisés :", file=sys.stderr)
                for issue in result.issues:
                    print(f"  - {issue}", file=sys.stderr)
                print(
                    "Relancer: python3 tools/sync_copilot_agents.py --write",
                    file=sys.stderr,
                )
                return 1
            print("✅ Profils GitHub Copilot synchronisés.")
            return 0

        result = write_sync(root)
        if result.changed:
            print("✅ Synchronisation GitHub Copilot terminée :")
            for change in result.changed:
                print(f"  - {change}")
        else:
            print("✅ Profils GitHub Copilot déjà synchronisés.")
        return 0
    except (ConversionError, OSError, UnicodeError) as exc:
        print(f"❌ {exc}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    raise SystemExit(main())
